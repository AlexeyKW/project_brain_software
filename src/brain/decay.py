"""brain decay — еженедельный job устаревания памяти (L2).

Детектирует:
  - anchor drift      — код под якорем изменился, запись не перепроверена;
  - ttl-истечения     — verified_at + ttl < сегодня;
  - семантические дубли — близость формулировок (Jaccard по токенам);
  - кандидатов в архив — superseded/rejected вне archive/.

Ничего не удаляется молча: результат — отчёт (опционально сохраняется
в .brain/state/decay-report.md), архивация — только явной командой
`brain decay --archive <ID>` и только через PR.
"""

from __future__ import annotations

import re
import shutil
from datetime import date, datetime
from pathlib import Path

from .cards import Card, load_cards
from .checks import anchor_drift
from .config import brain_dir

_TOKEN_RE = re.compile(r"[0-9A-Za-zА-Яа-яЁё_]{3,}")
DUPLICATE_THRESHOLD = 0.6

REPORT_PATH = "state/decay-report.md"


def _tokens(text: str) -> set[str]:
    return set(_TOKEN_RE.findall(text.lower()))


def _jaccard(a: set[str], b: set[str]) -> float:
    if not a or not b:
        return 0.0
    return len(a & b) / len(a | b)


def _not_archived(root: Path, card: Card) -> bool:
    return "archive" not in card.rel(root).split("/")


def ttl_expired(card: Card) -> str | None:
    """Причина истечения ttl или None."""
    ttl = card.meta.get("ttl")
    va = card.meta.get("verified_at")
    if not ttl or not va:
        return None
    try:
        days = int(str(ttl).rstrip("d"))
        vd = va.date() if isinstance(va, datetime) else (
            va if isinstance(va, date) else date.fromisoformat(str(va)[:10]))
    except (ValueError, TypeError):
        return None
    overdue = (date.today() - vd).days - days
    if overdue > 0:
        return f"verified_at {vd} + ttl {ttl} — просрочено на {overdue} дн."
    return None


def find_duplicates(cards: list[Card],
                    threshold: float = DUPLICATE_THRESHOLD) -> list[tuple[str, str, float]]:
    """Пары карточек с близкими формулировками (title + statement + тело)."""
    docs = {c.id: _tokens(" ".join([c.title, str(c.meta.get("statement", "")), c.body]))
            for c in cards}
    pairs = []
    ids = sorted(docs)
    for i, a in enumerate(ids):
        for b in ids[i + 1:]:
            sim = _jaccard(docs[a], docs[b])
            if sim >= threshold:
                pairs.append((a, b, sim))
    return sorted(pairs, key=lambda p: p[2], reverse=True)


def collect(root: Path) -> dict:
    cards = [c for c in load_cards(root) if _not_archived(root, c)]
    drift, expired = [], []
    for c in cards:
        for d in anchor_drift(c, root):
            drift.append((c, d))
        why = ttl_expired(c)
        if why:
            expired.append((c, why))
    duplicates = find_duplicates(cards)
    archive_candidates = [c for c in cards if c.status in ("superseded", "rejected")]
    return {"drift": drift, "expired": expired,
            "duplicates": duplicates, "archive": archive_candidates}


def render_report(root: Path, found: dict) -> tuple[str, int]:
    lines = [
        "<!-- GENERATED by `brain decay` — отчёт об устаревании памяти -->",
        "# Decay-отчёт",
        "",
        "Ничего не удаляется автоматически: разбор — через PR,",
        "архивация — `brain decay --archive <ID>`.",
        "",
        "## Anchor drift → needs-review",
    ]
    if found["drift"]:
        for c, d in found["drift"]:
            lines.append(f"- **{c.id}** ({c.rel(root)}): {d}")
    else:
        lines.append("- нет")
    lines.append("\n## TTL истёк → needs-review")
    if found["expired"]:
        for c, why in found["expired"]:
            lines.append(f"- **{c.id}** ({c.rel(root)}): {why}")
    else:
        lines.append("- нет")
    lines.append("\n## Возможные дубликаты")
    if found["duplicates"]:
        for a, b, sim in found["duplicates"]:
            lines.append(f"- **{a}** ↔ **{b}** — сходство {sim:.0%}; "
                         f"нужен явный `supersedes` или слияние")
    else:
        lines.append("- нет")
    lines.append("\n## Кандидаты в archive/")
    if found["archive"]:
        for c in found["archive"]:
            lines.append(f"- **{c.id}** ({c.status}) — {c.title}")
    else:
        lines.append("- нет")
    issues = (len(found["drift"]) + len(found["expired"])
              + len(found["duplicates"]) + len(found["archive"]))
    return "\n".join(lines) + "\n", issues


def archive_card(root: Path, card_id: str) -> int:
    card_id = card_id.upper()
    for c in load_cards(root):
        if c.id == card_id and _not_archived(root, c):
            dest = brain_dir(root) / "archive" / c.path.name
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.move(str(c.path), dest)
            print(f"brain decay: {card_id} → {dest.relative_to(root)}")
            print("Изменение попадёт в канон через PR — как любая запись памяти.")
            return 0
    print(f"brain decay: карточка {card_id} не найдена (или уже в archive/)")
    return 1


def run_decay(root: Path, cfg: dict, strict: bool = False,
              write: bool = False, archive: str | None = None) -> int:
    if archive:
        return archive_card(root, archive)
    report, issues = render_report(root, collect(root))
    print(report)
    if write:
        out = brain_dir(root) / REPORT_PATH
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(report, encoding="utf-8")
        print(f"отчёт сохранён: {out.relative_to(root)}")
    print(f"brain decay: {issues} находок"
          + (" — strict: СБОЙ" if strict and issues else ""))
    return 1 if strict and issues else 0
