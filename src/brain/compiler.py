"""Сборка HOT.md и generated-адаптеров из канонических записей.

Приоритет наполнения бюджета:
активные ограничения > блокеры > handoff > статус > карта > реестр решений.
Переполнение бюджета — ошибка сборки.
"""

from __future__ import annotations

import math
import re
from pathlib import Path

from . import templates
from .cards import Card, load_cards
from .config import brain_dir, get_budget, hot_path, token_chars


def estimate_tokens(text: str, chars_per_token: float = 3.0) -> int:
    return max(1, math.ceil(len(text) / chars_per_token))


def _md_section(text: str, needle: str) -> str:
    """Тело секции `## <needle>` (без заголовка), регистронезависимо."""
    out: list[str] = []
    capture = False
    for ln in text.splitlines():
        if ln.startswith("## "):
            if capture:
                break
            capture = needle.lower() in ln.lower()
            continue
        if capture:
            out.append(ln)
    return "\n".join(out).strip()


def _bullet_lines(text: str, limit: int) -> list[str]:
    lines = [ln.rstrip() for ln in text.splitlines()
             if ln.strip().startswith(("- ", "* ")) and "<" not in ln]
    return lines[:limit]


def _in_scope(card: Card, scope: str | None) -> bool:
    if not scope:
        return True
    cs = card.meta.get("scope") or []
    if not cs:
        return True  # глобальная запись
    from .checks import glob_match
    return any(glob_match(scope, s) or glob_match(s, scope) or s == scope
               for s in cs)


def _constraints_section(cards: list[Card], scope: str | None) -> str:
    cons = [c for c in cards if c.kind == "constraint"
            and c.status == "accepted" and _in_scope(c, scope)]
    cons.sort(key=lambda c: (c.meta.get("severity") != "blocking", c.id))
    lines = []
    for c in cons:
        sev = c.meta.get("severity", "soft")
        stmt = c.meta.get("statement", c.title)
        lines.append(f"- **{c.id}** [{sev}] {stmt}")
    return "## Активные ограничения\n" + ("\n".join(lines) if lines else "- нет")


def _status_sections(root: Path) -> tuple[str, str]:
    """(блокеры, в работе) из state/STATUS.md."""
    status_file = brain_dir(root) / "state" / "STATUS.md"
    if not status_file.is_file():
        return "", ""
    text = status_file.read_text(encoding="utf-8")
    blocked = _bullet_lines(_md_section(text, "Заблокировано"), 5)
    doing = _bullet_lines(_md_section(text, "В работе"), 5)
    b = "## Блокеры\n" + ("\n".join(blocked) if blocked else "- нет")
    w = "## В работе\n" + ("\n".join(doing) if doing else "- нет")
    return b, w


def _handoff_section(root: Path) -> str:
    hd = brain_dir(root) / "state" / "handoffs"
    files = sorted(hd.glob("*.md")) if hd.is_dir() else []
    if not files:
        return "## Последний handoff\n- нет"
    latest = files[-1]
    text = latest.read_text(encoding="utf-8")
    next_step = _md_section(text, "Следующий шаг")
    blockers = _md_section(text, "Блокеры")
    parts = [f"## Последний handoff\n- `{latest.name}`"]
    if next_step:
        parts.append("Следующий шаг: " + " ".join(next_step.split())[:300])
    if blockers:
        parts.append("Блокеры: " + " ".join(blockers.split())[:200])
    return "\n".join(parts)


def _map_section(root: Path) -> str:
    mi = brain_dir(root) / "map" / "index.md"
    if not mi.is_file():
        return "## Карта\n- нет"
    lines = []
    for ln in mi.read_text(encoding="utf-8").splitlines():
        s = ln.strip()
        if (s.startswith("- ") or s.startswith("## ")) and "<" not in s:
            lines.append(s.lstrip("# ").replace("- ", "- ", 1) if s.startswith("-") else f"- {s.lstrip('# ')}")
        if len(lines) >= 12:
            break
    return "## Карта (верхний уровень)\n" + ("\n".join(lines) if lines else "- нет")


def _registry_section(cards: list[Card], scope: str | None) -> str:
    decs = [c for c in cards if c.kind == "decision"
            and c.status in ("accepted", "proposed") and _in_scope(c, scope)]
    decs.sort(key=lambda c: c.id)
    lines = [f"- **{c.id}** — {c.title} *({c.status})*" for c in decs]
    return ("## Реестр решений (тела — по запросу: `brain why <id>`)\n"
            + ("\n".join(lines) if lines else "- нет"))


def build_hot(root: Path, cfg: dict, budget: int | None = None,
              scope: str | None = None) -> tuple[str, int, str | None]:
    """Возвращает (текст, токены, ошибка). Ошибка ≠ None ⇒ сборка не удалась."""
    cfg_budget = get_budget(cfg, budget)
    cpt = token_chars(cfg)
    cards = load_cards(root)
    project = cfg.get("project", root.name)

    header = (
        "<!-- GENERATED by `brain compile` — не редактировать. Канон: .brain/ -->\n"
        f"# HOT — {project}\n"
        f"Бюджет: ≤ {cfg_budget} токенов"
        + (f" · scope: `{scope}`" if scope else "")
        + "\n"
        "\nЭто проекция памяти проекта: состояние и намерения, не восстанавливаемые "
        "из кода. Тела карточек — по запросу (`brain why`, `brain search`).\n"
    )

    blockers, doing = _status_sections(root)
    sections = [
        ("constraints", _constraints_section(cards, scope)),
        ("blockers", blockers),
        ("handoff", _handoff_section(root)),
        ("status", doing),
        ("map", _map_section(root)),
        ("registry", _registry_section(cards, scope)),
    ]

    used = estimate_tokens(header, cpt)
    body_parts: list[str] = []
    for name, text in sections:
        if not text:
            continue
        cost = estimate_tokens(text, cpt)
        if used + cost <= cfg_budget:
            body_parts.append(text)
            used += cost
            continue
        # усечение построчно с указанием источника
        room = cfg_budget - used
        kept: list[str] = []
        for ln in text.splitlines():
            c = estimate_tokens(ln + "\n", cpt)
            if room - c < 8:  # оставить место под пометку об усечении
                break
            kept.append(ln)
            room -= c
        if name == "constraints" and len(kept) < len(text.splitlines()):
            return "", used, (
                "бюджет HOT переполнен активными ограничениями — это ошибка сборки. "
                "Сожмите формулировки (proposal с LLM-саммари) или поднимите "
                "budgets.hot в .brain/brain.yaml")
        kept.append("- … (усечено под бюджет; полный текст — в каноне `.brain/`)")
        body_parts.append("\n".join(kept))
        used = cfg_budget
        break

    hot = header + "\n" + "\n\n".join(body_parts) + "\n"
    return hot, estimate_tokens(hot, cpt), None


def render_adapter(name: str, cfg: dict, budget: int | None = None) -> str:
    return templates.AGENTS_ADAPTER.format(budget=get_budget(cfg, budget))


def adapter_targets(cfg: dict) -> list[tuple[str, Path]]:
    """[(имя, относительный путь)] из brain.yaml: adapters."""
    out = []
    for name in cfg.get("adapters", ["AGENTS.md"]):
        rel = templates.ADAPTER_FILES.get(name, name)
        out.append((name, Path(rel)))
    return out


def compile_all(root: Path, cfg: dict, budget: int | None = None,
                check: bool = False, scope: str | None = None) -> int:
    """Пишет HOT.md + адаптеры (или проверяет их при --check). Код выхода."""
    hot, tokens, err = build_hot(root, cfg, budget=budget, scope=scope)
    if err:
        print(f"brain compile: ОШИБКА: {err}")
        return 1

    artifacts: list[tuple[Path, str]] = [(hot_path(root), hot)]
    for name, rel in adapter_targets(cfg):
        artifacts.append((root / rel, render_adapter(name, cfg, budget)))

    if check:
        bad = [p for p, content in artifacts
               if not p.is_file() or p.read_text(encoding="utf-8") != content]
        if bad:
            print("brain compile --check: рассинхрон generated-артефактов:")
            for p in bad:
                print(f"  - {p}")
            print("Выполните `brain compile` и закоммитьте результат.")
            return 1
        print(f"brain compile --check: OK (HOT ≈ {tokens} токенов)")
        return 0

    for p, content in artifacts:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")
        print(f"  записано {p.relative_to(root)}")
    print(f"brain compile: HOT ≈ {tokens}/{get_budget(cfg, budget)} токенов")
    return 0
